#!/usr/bin/env node
/**
 * Writes src/components/replay/replay.scoped.css from replay.css (docstream's player styles, as copied).
 *
 *   node scripts/scope-replay-css.mjs
 *
 * docstream puts the player's rules in `@layer docstream.replay` under `:where()`, so a host's CSS wins.
 * That assumes the host's resets are layered too (Tailwind 4). This site's Tailwind 3 preflight and
 * forms plugin are unlayered, so they would beat every player rule: buttons lose their padding and
 * background, borders vanish. Here the layer is unwrapped and every selector is prefixed with
 * `:is(.replay-host, #replay-host)`, which matches the `.replay-host` wrapper with an id's specificity.
 * Every rule moves up by the same amount, so the player's own cascade is unchanged, and no reset
 * on the site can reach inside it.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'

const DIR = join(dirname(fileURLToPath(import.meta.url)), '../src/components/replay')
const SCOPE = ':is(.replay-host, #replay-host)'

const root = postcss.parse(readFileSync(join(DIR, 'replay.css'), 'utf8'))

root.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return
  rule.selectors = rule.selectors.map((selector) => `${SCOPE} ${selector}`)
})

// Unwrap each `@layer docstream.replay { … }`; keyframes nested in it come out with the rest.
root.walkAtRules('layer', (layer) => {
  layer.replaceWith(layer.nodes)
})

writeFileSync(
  join(DIR, 'replay.scoped.css'),
  `/* Generated by scripts/scope-replay-css.mjs from replay.css. Don't edit. */\n${root.toString()}`
)
console.log('wrote replay.scoped.css')

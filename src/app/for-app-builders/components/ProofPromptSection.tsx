'use client'

import { useState } from 'react'
import clsx from 'clsx'
import { Container } from '~/components/Container'

const PROMPT = `Use Replay QA (https://qa.replay.io) to test the web apps listed below. They were generated by our app builder.

Drive everything through the REST API at https://qa.replay.io/api/v1. Read the OpenAPI spec at /api/v1/openapi.json first; it documents the full workflow. Authenticate with my API token ("Authorization: Bearer lqa_..."), asking me for it if needed.

Your job:
1. Create one QA project per app URL below. Give it the target_url and a short note on what the app is for.
2. Let QA run. Poll each project's status and don't kick off explorations or test runs yourself; QA drives those.
3. When the runs finish, read the full root-caused report for each open bug.
4. Summarize the results for me: bugs per app, grouped by kind (broken functionality, performance, visual/accessibility, error handling, security), with the root cause and suggested fix for each. Don't change any code.

App URLs:
- [paste one or more URLs here]`

export function ProofPromptSection() {
  const [expanded, setExpanded] = useState(false)
  const [copied, setCopied] = useState(false)

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(PROMPT)
    } catch {
      const area = Object.assign(document.createElement('textarea'), { value: PROMPT })
      document.body.append(area)
      area.select()
      document.execCommand('copy')
      area.remove()
    }
    setCopied(true)
    window.setTimeout(() => setCopied(false), 2000)
  }

  return (
    <section className="relative isolate overflow-hidden bg-white py-16 md:py-24">
      <Container>
        <div className="mx-auto max-w-3xl">
          <h2 className="text-center text-2xl font-bold leading-tight text-gray-900 sm:text-3xl md:text-4xl">
            See the proof yourself.
          </h2>
          <p className="mx-auto mt-4 max-w-xl text-center text-base leading-relaxed text-gray-600 sm:text-lg">
            Drop this prompt into your coding agent, along with one or more URLs to web apps
            generated by your app builder, and see what Replay QA uncovers.
          </p>
          <div className="relative mt-10 overflow-hidden rounded-xl border border-gray-200 bg-gray-50">
            <button
              type="button"
              onClick={copy}
              className="absolute right-3 top-3 z-10 rounded-full bg-accent px-4 py-1.5 text-sm font-semibold text-white transition hover:bg-accent-light"
            >
              {copied ? 'Copied' : 'Copy prompt'}
            </button>
            <pre
              className={clsx(
                'whitespace-pre-wrap p-6 pr-32 font-mono text-[13px] leading-relaxed text-gray-800',
                !expanded &&
                  'max-h-44 overflow-hidden [mask-image:linear-gradient(to_bottom,black_55%,transparent)]'
              )}
            >
              {PROMPT}
            </pre>
          </div>
          <div className="mt-3 text-center">
            <button
              type="button"
              aria-expanded={expanded}
              onClick={() => setExpanded((v) => !v)}
              className="text-sm font-medium text-accent transition hover:opacity-80"
            >
              {expanded ? 'Hide full prompt' : 'Show full prompt'}
            </button>
          </div>
          <p className="mt-4 text-center text-sm text-gray-500">
            Needs a Replay QA API token. Free to start at{' '}
            <a
              href="https://qa.replay.io"
              target="_blank"
              rel="noopener noreferrer"
              className="font-medium text-accent transition hover:opacity-80"
            >
              qa.replay.io
            </a>
            , no credit card.
          </p>
        </div>
      </Container>
    </section>
  )
}
